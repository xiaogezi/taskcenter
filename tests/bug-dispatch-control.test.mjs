import assert from "node:assert/strict";
import test from "node:test";
import { spawn, execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { once } from "node:events";
import { isAllowedControlPath } from "../lib/control-proxy.mjs";

test("隔离 Control API 验证持久队列、来源门禁、宿主回执门禁和取消幂等", async context => {
  const dir = mkdtempSync(join(tmpdir(), "bug-control-"));
  const workspace = join(dir, "project"); mkdirSync(workspace);
  execFileSync("git", ["init", workspace], { stdio: "ignore" });
  execFileSync("git", ["-C", workspace, "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "commit", "--allow-empty", "-m", "isolated fixture"], { stdio: "ignore" });
  const baselineCommit = execFileSync("git", ["-C", workspace, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  const brain = "00000000-0000-4000-8000-000000000001";
  const executor = "00000000-0000-4000-8000-000000000002";
  const worktree = join(dir, "worktree");
  execFileSync("git", ["-C", workspace, "worktree", "add", "--detach", worktree, baselineCommit], { stdio: "ignore" });
  const ledger = join(dir, "ledger.json"), registry = join(dir, "registry.json");
  writeFileSync(ledger, JSON.stringify(["bug-isolated", "bug-host-isolated"].map(id => ({ id, sessionId: brain, title: "隔离 Bug", workspace, status: "in_progress", bug: { targetBranch: "main" } }))));
  writeFileSync(registry, JSON.stringify({ [brain]: { sessionId: brain, workspace }, [executor]: { sessionId: executor, workspace: worktree } }));
  const env = { ...process.env, TASKCENTER_CONTROL_PORT: String(39000 + process.pid % 1000), TASKCENTER_DISPATCH_DRY_RUN: "1", TASKCENTER_DISABLE_LIVE_SESSION_RECONCILIATION: "1", TASKCENTER_TASK_LEDGER_PATH: ledger, TASKCENTER_SESSION_REGISTRY_PATH: registry };
  for (const key of ["BUG_DISPATCHES", "DISPATCHES", "DELEGATIONS", "DASHBOARD", "TASK_EVENTS", "TASK_EVENT_IDS", "TASK_RECONCILE", "SESSION_MERGES", "ROUTING_CONTROL", "MCP_TOKEN", "CONTEXT_MANAGEMENT_PILOT_EVENTS"]) env[`TASKCENTER_${key}_PATH`] = join(dir, key.toLowerCase());
  env.TASKCENTER_SESSIONS_ROOT = join(dir, "sessions");
  const fixtureToken = "0".repeat(64);
  writeFileSync(env.TASKCENTER_MCP_TOKEN_PATH, fixtureToken, { mode: 0o600 });
  const child = spawn(process.execPath, ["scripts/control-server.mjs"], { env, stdio: ["ignore", "pipe", "pipe"] });
  context.after(async () => { child.kill(); if (child.exitCode === null) await once(child, "exit"); });
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("control startup timeout")), 10000);
    child.stdout.on("data", data => { if (String(data).includes("listening")) { clearTimeout(timer); resolve(); } });
    child.once("exit", code => { clearTimeout(timer); reject(new Error(`control exited ${code}`)); });
  });
  const base = `http://127.0.0.1:${env.TASKCENTER_CONTROL_PORT}`;
  const post = (path, body, extra = {}) => fetch(`${base}${path}`, { method: "POST", headers: { "Content-Type": "application/json", Origin: "http://localhost:3000", "X-TaskCenter-Action": "delegate", ...extra }, body: JSON.stringify(body) });
  assert.equal((await post("/tasks/bug-isolated/bug-dispatch", {}, { Origin: "https://untrusted.invalid" })).status, 403);
  assert.equal((await post("/tasks/bug-isolated/bug-dispatch", {})).status, 409);
  const response = await post("/tasks/bug-isolated/bug-dispatch", { baselineCommit });
  assert.equal(response.status, 202);
  const initial = await response.json();
  const duplicate = await (await post("/tasks/bug-isolated/bug-dispatch", {})).json();
  assert.equal(duplicate.idempotent, true); assert.equal(duplicate.records[0].id, initial.records[0].id);
  const snapshot = await (await fetch(`${base}/bug-dispatches`)).json();
  assert.equal(snapshot.records[0].wake.status, "unavailable");
  assert.equal(snapshot.capabilities.pause, false);
  assert.equal((await post("/bug-dispatches/host", { operation: "claim", session_id: brain })).status, 403);
  assert.equal(isAllowedControlPath("/bug-dispatches/host", "POST"), false);
  assert.equal(isAllowedControlPath("/tasks/bug-isolated/bug-dispatch/control", "POST"), true);
  const input = { action: "cancel", eventId: "cancel-once" };
  assert.equal((await (await post("/tasks/bug-isolated/bug-dispatch/control", input)).json()).records[0].status, "cancelled");
  assert.equal((await (await post("/tasks/bug-isolated/bug-dispatch/control", input)).json()).idempotent, true);
  const host = body => post("/bug-dispatches/host", { session_id: brain, ...body }, { "X-TaskCenter-Task": "mcp", "X-TaskCenter-MCP-Token": fixtureToken });
  const queued = await (await post("/tasks/bug-host-isolated/bug-dispatch", { baselineCommit })).json();
  const claim = await (await host({ operation: "claim", id: queued.records[0].id })).json();
  const receipt = { operation: "receipt", id: claim.record.id, claimToken: claim.record.claimToken, evidence: "Isolated host fixture, not a real desktop acceptance" };
  assert.equal((await host({ ...receipt, eventId: "creating", status: "creating", clientThreadId: "fixture-client-id" })).status, 200);
  assert.equal((await (await host({ operation: "claim", id: claim.record.id })).json()).resumed, true);
  assert.equal((await host({ ...receipt, eventId: "running", status: "running", visible: true, projectId: "fixture-project", threadId: executor })).status, 200);
  const cancelledRunning = await (await post("/tasks/bug-host-isolated/bug-dispatch/control", { action: "cancel", eventId: "request-only" })).json();
  assert.equal(cancelledRunning.records[0].status, "running");
  assert.equal(cancelledRunning.records[0].commands.at(-1).status, "requested");
});
